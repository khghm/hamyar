-- 040 — آواتار مشتری + نام کامل برای ورود با موبایل
--
-- ۱) ستون avatar_url: تا امروز عکس پروفایل فقط در حافظهٔ مرورگر نگه‌داری
--    می‌شد (data URL) و با رفرش از بین می‌رفت. حالا فایل در باکت عمومی
--    `images/avatars/` آپلود و آدرسش اینجا ذخیره می‌شود.
-- ۲) display_name از قبل وجود دارد؛ برای کاربرانی که فقط با شماره وارد
--    می‌شوند، نام در همان ستون ذخیره می‌شود (اولین ورود از کاربر پرسیده
--    می‌شود و اگر رد کند، شماره به‌عنوان جایگزین می‌ماند).

alter table public.profiles
  add column if not exists avatar_url text;

comment on column public.profiles.avatar_url is
  'آدرس تصویر آواتار مشتری در Storage عمومی (images/avatars/…)';
