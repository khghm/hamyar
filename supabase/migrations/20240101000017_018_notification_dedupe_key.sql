-- 018 — `dedupe_key` برای اعلان‌های خودکار
--
-- ── مسئله ────────────────────────────────────────────────────────────────────
-- `pushNotification` در `src/store.tsx` یک `key` می‌گیرد و قبل از ساخت
-- اعلان، لیست را می‌گردد تا همان رویداد دوباره اعلان نکند:
--
--   if (key && notificationsRef.current.some(n => n.dedupeKey === key)) return;
--
-- ولی `dedupeKey` فقط روی شیء درون‌حافظه‌ای ست می‌شد و هرگز به Postgres
-- نمی‌رفت. جدول `notifications` چنین ستونی نداشت و
-- `toNotification` در `src/api/notifications.ts` هم آن را نمی‌خواند.
--
-- نتیجه: بعد از هر hydration از سرور، تمام اعلان‌ها `dedupeKey === undefined`
-- بودند و guard هیچ‌وقت آن‌ها را نمی‌دید. اثر عملی آن در دیتابیس کمتر از یک
-- ساعت قابل اندازه‌گیری بود: ۳۷۳ ردیف از نوع `stock` با فقط ۲۰ پیام
-- یکتا — یعنی هر بار که صفحهٔ مدیر باز می‌شد، برای هر محصولِ زیر آستانه یک
-- اعلان سراسری (`user_id is null`) دوباره درج می‌شد و به همهٔ مدیران
-- نمایش داده می‌شد.
--
-- ── راه‌حل ───────────────────────────────────────────────────────────────────
-- ستون در پایگاه‌داده نگه‌داری می‌شود تا پس از بارگذاری مجدد هم بازسازی شود.
-- یکتایی فقط برای ردیف‌های سراسری (`user_id is null`) لازم است: اعلانِ شخصیِ
-- هر کاربر باید برای خودش بماند و با اعلانِ کاربر دیگر تداخل نکند.
--
-- اعلان‌هایی که کلید ندارند (ساختهٔ کارمند، اعلان‌های قدیمی) با
-- `null` می‌مانند و از شرط یکتایی مستثنا هستند، چون در SQL چند `null`
-- با هم یکتا محسوب نمی‌شوند.
--
-- پاکسازی ردیف‌های تکراری: برای هر کلید، تازه‌ترین ردیف سراسری می‌ماند
-- و بقیه حذف می‌شوند، تا اعلان‌های انباشتهٔ گذشته یک‌بار پاک شوند.

-- =========================================================================
-- ۱) ستون کلید
-- =========================================================================
alter table notifications add column if not exists dedupe_key text;

comment on column notifications.dedupe_key is
  'کلید یکتای رویداد برای جلوگیری از اعلان تکراری؛ فقط برای ردیف‌های سراسری یکتاست.';

-- =========================================================================
-- ۲) کلیدگذاری اعلان‌های سراسریِ انباشته
--
--    فقط نوع `stock`، چون فقط همین یکی از پایین مشترکِ قابل بازسازی است:
--    پیامش نام محصول و موجودی را دارد، پس همان محصول با همان موجودی یک کلید
--    می‌گیرد و ۳۷۳ ردیف به ۲۰ ردیف تازه‌تر تبدیل می‌شود.
--
--    سایر انواع عمداً کلید نمی‌گیرند: کلیدشان به شناسهٔ موجودیت گره خورده
--    (سفارش، نظر، تیکت) که در ردیف ذخیره نشده، و بازسازیِ حدسی با
--    `type || link` کلیدهای متفاوت را یکی می‌کرد و اعلان‌های به‌رسمیت‌شناخته‌شده
--    را حذف می‌کرد. ردیف‌های بدون کلید از شرط یکتایی مستثنا هستند.
-- =========================================================================
update notifications
set dedupe_key = 'stock-name-' || substring(message from 'موجودی «([^»]+)»')
where dedupe_key is null
  and user_id is null
  and type = 'stock'
  and substring(message from 'موجودی «([^»]+)»') is not null;

-- =========================================================================
-- ۳) پاکسازی تکراری‌ها: برای هر کلید تازه‌ترین ردیف می‌ماند
--
--    مقایسه با (created_at, id) است، نه فقط created_at: ردیف‌هایی که در
--    یک تراکنش ساخته شده‌اند now() یکسانی دارند و با مقایسهٔ صرفاً
--    زمانی هیچ‌کدام «تازه‌تر» به نظر نمی‌رسد، پس هر دو می‌مانند و
--    ساخت ایندکس یکتا در گام بعدی با 23505 شکست می‌خورد. شناسه
--    به‌عنوان شکستهٔ تساوی، حذف را قطعی می‌کند.
-- =========================================================================
delete from notifications n
using notifications keep
where n.user_id is null
  and keep.user_id is null
  and n.dedupe_key is not null
  and keep.dedupe_key = n.dedupe_key
  and (keep.created_at > n.created_at
       or (keep.created_at = n.created_at and keep.id > n.id));

-- =========================================================================
-- ۴) یکتایی محدود به اعلان‌های سراسری
--
--    بعد از گام‌های بالا ساخته می‌شود، نه قبل از آن: کلیدهای گام ۲ روی
--    چندین ردیف تکراری می‌نشینند و ساخت زودهنگام ایندکس، همان گام را
--    با خطای یکتایی از بین می‌برد.
-- =========================================================================
create unique index if not exists idx_notifications_dedupe_broadcast
  on notifications(dedupe_key)
  where dedupe_key is not null and user_id is null;

-- =========================================================================
-- ۵) ایندکس کمکی برای نشستن سریع guard روی لیست اعلان‌ها
-- =========================================================================
create index if not exists idx_notifications_created on notifications(created_at desc);