const slug = (i) => 's' + (i + 1);

const tsLines = S.map((s, i) =>
  `  { id: '${slug(i)}', name: '${s[0]}', category: '${s[1]}', basePrice: ${s[2]}, unit: '${s[3]}', description: '${s[4]}', active: true },`
).join('\n');

const sqlLines = S.map((s, i) =>
  `  ('${slug(i)}', '${s[0]}', '${s[1]}', ${s[2]}, '${s[3]}', '${s[4]}', true, null, null),`
).join('\n').replace(/,$/, ';');

// --- patch TS files ---
for (const f of ['src/data/seed.ts', 'src/state/catalogStore.ts']) {
  let t = fs.readFileSync(f, 'utf8');
  const re = /(const |export const )initialServices: Service\[\] = \[[\s\S]*?\n\];/;
  if (!re.test(t)) { console.error('NOT FOUND in', f); process.exit(1); }
  t = t.replace(re, (m, p) => `${p}initialServices: Service[] = [\n${tsLines}\n];`);
  fs.writeFileSync(f, t);
  console.log('patched', f, '-', S.length, 'services');
}

// --- patch SQL ---
{
  const f = 'supabase/seed.sql';
  let t = fs.readFileSync(f, 'utf8');
  const start = t.indexOf('insert into services');
  if (start < 0) { console.error('SQL block not found'); process.exit(1); }
  const end = t.indexOf(');', start);
  if (end < 0) { console.error('SQL end not found'); process.exit(1); }
  const block = `insert into services (sku, name, category, base_price, unit, description, active,\n                      fields, docs) values\n${sqlLines}`;
  t = t.slice(0, start) + block + t.slice(end + 2);
  t = t.replace('-- === 5) Services (61: s1..s61)', `-- === 5) Services (${S.length}: s1..s${S.length})`);
  fs.writeFileSync(f, t);
  console.log('patched', f);
}
